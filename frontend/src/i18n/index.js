export const normalizeLanguage = (language) =>
  language === 'en' || language === 'en-US' ? 'en-US' : 'zh-CN';

export const getMessages = (language) => messages[normalizeLanguage(language)] || messages['zh-CN'];

export const useAppI18n = () => {
  const language = useSelector((state) => state?.ui?.preferences?.language || 'zh-CN');
  const locale = normalizeLanguage(language);

  const t = useMemo(() => {
    const currentMessages = getMessages(locale);
    return (key, fallback = key) => currentMessages[key] || fallback;
  }, [locale]);

  return { language: locale, t };
};
